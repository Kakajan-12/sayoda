import React from "react";

/**
 * Поле-ловушка вместо капчи.
 *
 * Капча стояла на всех трёх формах и отбивала даже верный ответ. Виновата
 * была не картинка: код хранился в сессии, кука сессии выдавалась с
 * SameSite=Lax, и с локальной сборки на localhost:3000 браузер её на
 * api.sayodatravel.com не возвращал — сессия каждый раз была пустая.
 * Вторая беда: сессии лежали в памяти процесса, и перезапуск контейнера
 * стирал их все разом, обрывая заполнение формы на ровном месте.
 *
 * Здесь поля не видно и до него не добраться: оно уведено за левый край
 * экрана, убрано из обхода клавиатурой и скрыто от скринридера.
 *
 * Поле называется contact_ref, а не website, и подписи «Website» у него
 * больше нет. Прежнее имя было прямым указанием автозаполнению браузера и
 * менеджерам паролей: сюда подставляется адрес сайта. Они и подставляли —
 * 15 сентября в логах бэкенда две заявки подряд, отброшенные как ботовские,
 * ровно в то время, когда их отправлял заказчик. Человек видел «Заявка
 * отправлена», а заявки не было ни в админке, ни в почте. Атрибут
 * autoComplete="off" от этого не спасает: для полей, опознанных как адрес
 * сайта, Chrome соблюдает его не всегда.
 *
 * Имя обязано совпадать с тем, что ждёт botTrap на сервере. Там на время
 * перехода приняты оба — и старое, и новое.
 *
 * Сама ловушка больше не отбрасывает обращение: сервер только помечает его
 * в теме письма. Цена ошибки несимметрична — лишний спам стоит секунды
 * внимания, потерянная заявка на тур стоит тысячи долларов.
 *
 * Уводим за край, а не прячем display:none: скрытые таким образом поля
 * многие боты пропускают, и ловушка не срабатывает.
 *
 * Значение держим в состоянии формы, а не в самом поле. Формы отправляются
 * не браузером, а fetch с телом из состояния: поле, о котором состояние не
 * знает, в запрос бы просто не попало. Так ловушка срабатывает в обоих
 * случаях — и когда бот забирает разметку и шлёт запрос сам, и когда он
 * водит настоящий браузер и печатает в поле.
 */
export default function BotTrap({
  value,
  onChange,
}: {
  value: string;
  onChange: (value: string) => void;
}) {
  return (
    <div
      className="absolute -left-[9999px] h-px w-px overflow-hidden"
      aria-hidden="true"
    >
      {/* Подпись нужна разметке, но текста «Website» в ней быть не должно:
          именно по нему автозаполнение и опознаёт поле. */}
      <label htmlFor="contact_ref">Leave this field empty</label>
      <input
        id="contact_ref"
        name="contact_ref"
        type="text"
        tabIndex={-1}
        autoComplete="off"
        value={value}
        onChange={(e) => onChange(e.target.value)}
      />
    </div>
  );
}
