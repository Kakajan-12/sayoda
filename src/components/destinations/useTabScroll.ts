"use client";

import { useEffect, useRef } from "react";
import { usePathname } from "@/i18n/navigation";
import { keepScrollOnNextNavigation } from "@/lib/keepScroll";

/**
 * Метка на области содержимого под вкладками. Нужна на один случай — когда
 * браузер сам обрезал прокрутку, см. ниже.
 */
export const CONTENT_ANCHOR = "destination-content";

/**
 * Переключение вкладки не двигает экран.
 *
 * Раньше нажатие на «Пересечение границ» отбрасывало к шапке и баннеру в
 * шестьсот пикселей, а до нового текста приходилось прокручивать вниз самому.
 * Разметка при этом не пересоздавалась — баннер, его картинка и боковое меню
 * оставались теми же узлами, — но со стороны это неотличимо от перезагрузки.
 *
 * Наверх отматывал не роутер, а ScrollToTop из корневого макета: он делает это
 * при каждой смене адреса и о scroll={false} у ссылки ничего не знает. Поэтому
 * ссылка ставит ему разовую отметку «не трогать» (lib/keepScroll), и экран
 * остаётся ровно там, где стоял: человек смотрит в одну точку и получает в ней
 * другой текст.
 *
 * Отметка живёт до ближайшей смены адреса, поэтому ставится только когда переход
 * точно произойдёт: не на повторное нажатие уже открытой вкладки и не на клик с
 * Ctrl или средней кнопкой — там ссылка открывается в новой вкладке, а текущая
 * страница остаётся на месте, и отметка повисла бы до следующего перехода.
 *
 * Единственное вмешательство в прокрутку — когда её обрезал сам браузер. Вкладки
 * очень разной длины: уходя с середины длинного списка туров на «Пересечение
 * границ» с его единственным абзацем, человек стоял бы глубже, чем новая
 * страница вообще позволяет прокрутить, и оказался бы в подвале. Тогда остаться
 * на месте уже невозможно, и вместо подвала подводим к вкладкам.
 *
 * Целью служит область содержимого, а не сама панель вкладок: панель липкая, а
 * у прилипшего элемента scrollIntoView считает, что он уже на месте, и не
 * двигает страницу вовсе. Отступ под шапку и панель задаёт scroll-mt-44 на
 * самой цели — scrollIntoView учитывает scroll-margin-top.
 *
 * @returns обработчик для onClick ссылки — принимает её адрес и событие.
 */
export default function useTabScroll() {
  const pathname = usePathname();
  /** Что нажали и откуда — чтобы после перехода понять, обрезал ли нас браузер. */
  const pending = useRef<{ href: string; from: number } | null>(null);

  useEffect(() => {
    const click = pending.current;
    pending.current = null;

    // Сравниваем с адресом, а не просто «был ли клик»: под этими вкладками
    // живут и обычные ссылки — на страницу достопримечательности, на другое
    // направление из подвала. Их прокручивает наверх ScrollToTop, и это верно;
    // вмешиваться нужно только в переходы по самим вкладкам.
    if (click === null || click.href !== pathname) return;

    // Прокрутка уцелела — экран стоит там же, где стоял. Не трогаем.
    if (window.scrollY >= click.from) return;

    document.getElementById(CONTENT_ANCHOR)?.scrollIntoView();
  }, [pathname]);

  return (href: string, event: React.MouseEvent) => {
    const opensElsewhere =
      event.button !== 0 ||
      event.metaKey ||
      event.ctrlKey ||
      event.shiftKey ||
      event.altKey;
    if (opensElsewhere || href === pathname) return;

    keepScrollOnNextNavigation();
    pending.current = { href, from: window.scrollY };
  };
}
