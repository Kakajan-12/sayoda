"use client";

import { useEffect, useRef } from "react";
import { usePathname } from "@/i18n/navigation";

/**
 * Метка на панели вкладок страны — к ней подводится экран после любого
 * переключения, и с верхнего ряда вкладок, и из бокового меню виз.
 */
export const TABS_ANCHOR = "destination-tabs";

/**
 * Куда встать после переключения вкладки.
 *
 * По умолчанию Next после перехода отматывает страницу в самое начало.
 * На страницах направления над вкладками стоит баннер в шестьсот пикселей,
 * и переключение выглядело так: человек нажимает «Пересечение границ»,
 * экран уезжает наверх, и он снова видит ту же шапку и тот же баннер, а до
 * нового текста надо прокручивать вниз самому. Разметка при этом не
 * пересоздаётся — баннер, картинка и боковое меню остаются теми же узлами,
 * меняется только содержимое, — но со стороны это неотличимо от полной
 * перезагрузки страницы.
 *
 * Поэтому ссылки вкладок идут с scroll={false}, а решение, куда встать,
 * принимается здесь: к самой панели вкладок. Тогда новый раздел всегда
 * оказывается сразу под ней — откуда бы ни пришли, от баннера сверху или
 * из середины длинного списка туров, где простое «остаться на месте»
 * выбросило бы в подвал: короткая вкладка вроде «Пересечение границ»
 * заканчивается там, где длинная только начинается.
 *
 * Отступ сверху задаёт scroll-mt-32 на самой цели: scrollIntoView учитывает
 * scroll-margin-top, и вкладки встают под липкой шапкой, а не за ней.
 *
 * К той же панели подводит и боковое меню виз, хотя живёт оно уровнем ниже:
 * так после выбора раздела на экране остаются оба уровня навигации — вкладки
 * страны, под ними список разделов, под ним текст. Если подводить к самому
 * меню, верхние вкладки уезжают под шапку, и человек теряет из виду, где он.
 *
 * Цель ищется по id, а не через ref: во-первых, на неё ссылаются из двух
 * разных мест дерева, во-вторых, боковое меню липкое, а у прилипшего элемента
 * scrollIntoView считает, что он уже на месте, и не двигает страницу вовсе.
 *
 * @returns обработчик для onClick ссылки — принимает её адрес.
 */
export default function useTabScroll() {
  const pathname = usePathname();
  /** Адрес, который человек только что нажал. */
  const target = useRef<string | null>(null);

  useEffect(() => {
    const wanted = target.current;
    target.current = null;

    // Сравниваем с адресом, а не просто «был ли клик»: под этими вкладками
    // живут и обычные ссылки — на страницу достопримечательности, на другое
    // направление из подвала. Их Next прокручивает наверх сам, и это верно;
    // вмешиваться нужно только в переходы по самим вкладкам.
    if (wanted === null || wanted !== pathname) return;

    document.getElementById(TABS_ANCHOR)?.scrollIntoView();
  }, [pathname]);

  return (href: string) => {
    target.current = href;
  };
}
