"use client";

import { usePathname } from "@/i18n/navigation";

/**
 * Надпись на обложке направления.
 *
 * Обложка общая на все пять страниц страны — она в макете, — и заголовком
 * первого уровня быть может только на одной из них. Раньше им была везде:
 * у страницы отелей, достопримечательностей и визы главным заголовком стояло
 * «Travel to Turkmenistan». Для поиска это значит, что самый весомый
 * заголовок страницы про отели про отели не говорит ни слова.
 *
 * Теперь h1 остаётся только на обзоре страны, а на вкладках обложка — просто
 * надпись, и заголовок первого уровня даёт содержимое вкладки.
 *
 * Адрес читается на клиенте, потому что макет своего маршрута не знает:
 * params у него только страна, а какая вкладка открыта — нет. То же самое
 * делает соседняя панель вкладок, когда подсвечивает активную.
 *
 * Вид надписи от уровня заголовка не зависит — классы те же, на экране
 * разницы нет.
 */
export default function HeroHeading({
  slug,
  html,
  className,
}: {
  slug: string;
  /** Заголовок из админки: допускает <br/> для переноса. */
  html: string;
  className: string;
}) {
  const pathname = usePathname();
  const обзор = pathname === `/destinations/${slug}`;
  const Тег = обзор ? "h1" : "p";

  return (
    <Тег className={className} dangerouslySetInnerHTML={{ __html: html }} />
  );
}
