/**
 * Разовая отметка «не отматывать страницу в начало».
 *
 * ScrollToTop в корневом макете прокручивает страницу наверх при каждой смене
 * адреса. Почти везде это верно, но не при переключении вкладок направления:
 * там меняется только содержимое под вкладками, и человек ждёт, что в той же
 * точке экрана появится другой текст, а не что его увезут к баннеру.
 *
 * Проп scroll={false} у ссылки тут не помогает — он отключает прокрутку самого
 * роутера, а ScrollToTop прокручивает сам и о нём не знает. Это и сбивало с
 * толку при отладке: ссылки уже стояли с scroll={false}, а страница всё равно
 * прыгала наверх.
 *
 * Отметку ставит ссылка в момент нажатия, а снимает ScrollToTop, когда решает,
 * прокручивать ли. Живёт она ровно до ближайшей смены адреса, поэтому ставить
 * её нужно только когда переход точно произойдёт.
 */
let keep = false;

/** Пропустить прокрутку наверх у следующего перехода. */
export function keepScrollOnNextNavigation() {
  keep = true;
}

/** Забирает отметку: вернёт true один раз, дальше снова false. */
export function takeKeepScroll() {
  const value = keep;
  keep = false;
  return value;
}
