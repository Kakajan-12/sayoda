import {defineRouting} from 'next-intl/routing';

export const routing = defineRouting({
  locales: ['en', 'ru', 'tk'],

  defaultLocale: 'en',

  /*
   * Корень сайта всегда открывает английскую версию.
   *
   * По умолчанию next-intl смотрит на язык браузера и куку с прошлым
   * выбором, поэтому язык по умолчанию срабатывал только у тех, у кого
   * браузер не просит ничего знакомого: посетитель с русским браузером
   * попадал на /ru, с туркменским — на /tk, и увидеть, что на самом деле
   * настроено, было нельзя.
   *
   * Сайт продаёт туры по Туркменистану иностранцам, и английская версия
   * должна быть лицом по умолчанию, а не зависеть от того, кто зашёл.
   *
   * Оговорка: этот флаг в next-intl выключает не только определение по
   * браузеру, но и запоминание выбранного языка в куке — они там связаны
   * одной настройкой. То есть посетитель, переключившийся на русский,
   * при следующем заходе на голый адрес снова увидит английский. Ссылки
   * вида /ru/tours при этом работают как работали, и переключатель языка
   * на месте.
   */
  localeDetection: false,
});
