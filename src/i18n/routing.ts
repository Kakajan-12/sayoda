import {defineRouting} from 'next-intl/routing';

export const routing = defineRouting({
  locales: ['en', 'ru', 'tk'],

  defaultLocale: 'en',

  /*
   * Корень сайта всегда открывает английскую версию.
   *
   * По умолчанию next-intl смотрит на язык браузера и куку с прошлым
   * выбором, поэтому язык по умолчанию срабатывал только у тех, у кого
   * браузер не просит ничего знакомого: посетитель с русским браузером
   * попадал на /ru, с туркменским — на /tk, и увидеть, что на самом деле
   * настроено, было нельзя.
   *
   * Сайт продаёт туры по Туркменистану иностранцам, и английская версия
   * должна быть лицом по умолчанию, а не зависеть от того, кто зашёл.
   *
   * Посетитель, переключившийся на русский, при следующем заходе на голый
   * адрес снова увидит английский. Ссылки вида /ru/tours работают как
   * работали, и переключатель языка на месте.
   */
  localeDetection: false,

  /*
   * Куку с языком не ставим.
   *
   * Раньше здесь стояло, что localeDetection выключает и её тоже. Это
   * неверно: в next-intl это две независимые настройки, и кука писалась
   * по-прежнему. Видно было прямо в ответе боевого сайта —
   * Set-Cookie: NEXT_LOCALE=ru на каждой странице.
   *
   * А ответ с кукой общий кэш хранить не может: Vercel помечал такие
   * страницы private, no-store и не кэшировал ни одной. Из-за этого возврат
   * статического рендера не дал ничего — страницы по-прежнему собирались
   * на каждый запрос.
   *
   * Читать эту куку всё равно некому: определением языка занимается
   * localeDetection, а он выключен. То есть она была записью в никуда
   * ценой кэша всего сайта.
   */
  localeCookie: false,

  /*
   * Заголовок Link с языковыми версиями не отдаём.
   *
   * next-intl ставит его сам, и он повторял то, что уже есть в двух
   * местах: в <head> каждой страницы и в sitemap.xml. Само по себе
   * дублирование безобидно, но x-default в нём указывал на корень сайта,
   * а в head — на /en. Корень отвечает редиректом 307 на /en, то есть
   * поисковику приходили два разных адреса «версии по умолчанию» для
   * одной страницы, причём один из них — редирект.
   *
   * Оставляем один источник: теги в head, где x-default указывает на
   * конечный адрес. Карта сайта повторяет их же.
   */
  alternateLinks: false,
});
